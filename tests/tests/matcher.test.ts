describe('duplicate prevention', () => {
  it('does not duplicate a test file matched by both convention and import', () => {
    // src/foo.test.ts exists (convention match) AND imports src/foo.ts (import match).
    const testContent = `import { foo } from './foo';\n`;
    const result = matchTests(
      [af('src/foo.ts')],
      REPO,
      makeFs(['src/foo.test.ts'], { 'src/foo.test.ts': testContent }),
    );
    const files = result[0]!.testFiles;
    expect(new Set(files).size).toBe(files.length); // all unique
    expect(files).toContain('src/foo.test.ts');
    expect(files).toHaveLength(1);
  });
});

