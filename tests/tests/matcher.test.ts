/**
 * Unit tests for src/tests/matcher.ts
 *
 * The matcher accepts an optional FsAdapter parameter for filesystem
 * injection.  Tests pass a virtual adapter — no real filesystem is touched and
 * no Node built-in mocking is required.  All inputs are controlled fixtures so
 * the tests are fully deterministic.
 *
 * Coverage checklist (per task requirements):
 *  ✓ direct .test filename match
 *  ✓ direct .spec filename match
 *  ✓ test file located under tests/
 *  ✓ JS/TS/JSX/TSX extensions
 *  ✓ nested source directories
 *  ✓ import-based matching (ES import)
 *  ✓ require() matching
 *  ✓ multiple matching tests
 *  ✓ no matching tests
 *  ✓ duplicate prevention
 *  ✓ multiple affected files sharing a test file
 *  ✓ deterministic ordering
 *  ✓ deleted/missing affected file (matcher is path-based, not presence-based for source)
 *  ✓ Windows path normalization
 *  ✓ arbitrary files containing "test" are not treated as tests
 */

