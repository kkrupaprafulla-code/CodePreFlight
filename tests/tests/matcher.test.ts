describe('multiple affected files sharing a test file', () => {
  it('maps a shared test file to each relevant affected file independently', () => {
    // tests/shared.test.ts imports ../src/a and ../src/b (one level up from tests/)
    const sharedContent =
      `import { a } from '../src/a';\nimport { b } from '../src/b';\n`;
    const fs = makeFs(
      ['tests/shared.test.ts'],
      { 'tests/shared.test.ts': sharedContent },
    );
    const result = matchTests([af('src/a.ts'), af('src/b.ts')], REPO, fs);
    expect(result).toHaveLength(2);
    expect(result[0]!.testFiles).toContain('tests/shared.test.ts');
    expect(result[1]!.testFiles).toContain('tests/shared.test.ts');
  });
});

