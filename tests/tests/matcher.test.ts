describe('testFileImportsSource (pure helper)', () => {
  it('returns true when content contains a bare import matching the source', () => {
    const testAbs = repoPath('tests/foo.test.ts');
    const srcAbs = repoPath('src/foo.ts');
    // The import specifier is relative from tests/ to src/:  ../../src/foo
    // On any OS, path.resolve(dirname(testAbs), '../../src/foo') === srcAbs-without-ext.
    const rel = path.relative(path.dirname(testAbs), repoPath('src/foo'));
    const content = `import { x } from './${rel.replace(/\\/g, '/')}';\n`;
    const adapter: FsAdapter = {
      existsSync: () => false,
      readdirSync: () => [],
      readFileSync: () => content,
    };
    expect(testFileImportsSource(testAbs, srcAbs, adapter)).toBe(true);
  });

  it('returns false when no import resolves to the source', () => {
    const testAbs = repoPath('tests/foo.test.ts');
    const srcAbs = repoPath('src/foo.ts');
    const content = `import { x } from './other';\n`;
    const adapter: FsAdapter = {
      existsSync: () => false,
      readdirSync: () => [],
      readFileSync: () => content,
    };
    expect(testFileImportsSource(testAbs, srcAbs, adapter)).toBe(false);
  });

  it('returns false when readFileSync throws', () => {
    const testAbs = repoPath('tests/foo.test.ts');
    const srcAbs = repoPath('src/foo.ts');
    const adapter: FsAdapter = {
      existsSync: () => false,
      readdirSync: () => [],
      readFileSync: () => { throw new Error('ENOENT'); },
    };
    expect(testFileImportsSource(testAbs, srcAbs, adapter)).toBe(false);
  });

  it('matches when the import specifier includes a source extension (.ts)', () => {
    // Some code uses 'from ../../src/foo.ts' explicitly (e.g. Deno style).
    const testAbs = repoPath('tests/foo.test.ts');
    const srcAbs = repoPath('src/foo.ts');
    const rel = path.relative(path.dirname(testAbs), repoPath('src/foo.ts'));
    const content = `import type { Foo } from './${rel.replace(/\\/g, '/')}';\n`;
    const adapter: FsAdapter = {
      existsSync: () => false,
      readdirSync: () => [],
      readFileSync: () => content,
    };
    expect(testFileImportsSource(testAbs, srcAbs, adapter)).toBe(true);
  });
});
