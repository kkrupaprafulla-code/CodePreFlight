describe('import-based matching', () => {
  it('finds a test that uses ES import with from clause pointing to the source', () => {
    // tests/utils/helper.other.test.ts imports src/utils/helper — relative: ../../src/utils/helper
    const testContent = `import { foo } from '../../src/utils/helper';\n`;
    const fs = makeFs(
      ['tests/utils/helper.other.test.ts'],
      { 'tests/utils/helper.other.test.ts': testContent },
    );
    const result = matchTests([af('src/utils/helper.ts')], REPO, fs);
    expect(result[0]!.testFiles).toContain('tests/utils/helper.other.test.ts');
  });

  it('finds a test that imports with the .ts extension included', () => {
    // tests/foo.other.test.ts importing ../src/foo.ts (one level up from tests/ to repo root)
    const testContent = `import type { Foo } from '../src/foo.ts';\n`;
    const fs = makeFs(
      ['tests/foo.other.test.ts'],
      { 'tests/foo.other.test.ts': testContent },
    );
    const result = matchTests([af('src/foo.ts')], REPO, fs);
    expect(result[0]!.testFiles).toContain('tests/foo.other.test.ts');
  });

  it('finds a test that uses require() pointing to the source', () => {
    // tests/bar.test.ts requires ../src/utils/bar — relative from tests/ to src/utils/bar
    const testContent = `const { bar } = require('../src/utils/bar');\n`;
    const fs = makeFs(
      ['tests/bar.test.ts'],
      { 'tests/bar.test.ts': testContent },
    );
    const result = matchTests([af('src/utils/bar.ts')], REPO, fs);
    expect(result[0]!.testFiles).toContain('tests/bar.test.ts');
  });

  it('does NOT match a test whose import does not resolve to the source', () => {
    const testContent = `import { x } from './other';\n`;
    const fs = makeFs(
      ['tests/unrelated.test.ts'],
      { 'tests/unrelated.test.ts': testContent },
    );
    const result = matchTests([af('src/foo.ts')], REPO, fs);
    expect(result[0]!.testFiles).toHaveLength(0);
  });
});

