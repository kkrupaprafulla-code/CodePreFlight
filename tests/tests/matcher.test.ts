describe('filename convention — .test', () => {
  it('matches src/foo.test.ts alongside the source file', () => {
    const result = matchTests([af('src/foo.ts')], REPO, makeFs(['src/foo.test.ts']));
    expect(result).toHaveLength(1);
    expect(result[0]!.affectedFile).toBe('src/foo.ts');
    expect(result[0]!.testFiles).toContain('src/foo.test.ts');
  });

  it('matches tests/foo.test.ts under the tests/ root directory', () => {
    const result = matchTests([af('src/foo.ts')], REPO, makeFs(['tests/foo.test.ts']));
    expect(result[0]!.testFiles).toContain('tests/foo.test.ts');
  });
});

