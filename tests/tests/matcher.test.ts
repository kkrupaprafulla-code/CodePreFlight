// ---------------------------------------------------------------------------
// Virtual filesystem helpers
// ---------------------------------------------------------------------------

/**
 * Use a virtual repo root that is consistent with what path.resolve() would
 * produce for it, so all paths generated by the matcher (which uses path.join
 * and path.resolve internally) key against the same values in the adapter.
 *
 * On POSIX: path.resolve('/virtual-repo') === '/virtual-repo'.
 * On Windows: path.resolve('/virtual-repo') === 'C:\\virtual-repo'.
 *
 * We deliberately use a path that will never exist on disk and call
 * path.resolve on it so the adapter keys always match.
 */
const REPO_RAW = '/virtual-cpf-test-repo';
const REPO = path.resolve(REPO_RAW);

/** Normalise any path to forward-slash representation for adapter key lookup. */
function norm(p: string): string {
  return p.replace(/\\/g, '/');
}

/** Build an absolute path under REPO from a POSIX-relative path. */
function repoPath(rel: string): string {
  // Join each POSIX segment individually so path.join handles OS separators.
  return path.join(REPO, ...rel.split('/'));
}

/** Build a minimal AffectedFile fixture. */
function af(p: string, depth = 0): AffectedFile {
  return { path: p, depth };
}

/**
 * Build a virtual FsAdapter from a list of POSIX-relative file paths and an
 * optional map of POSIX-relative path → file content.
 *
 * `existsSync` returns true for any path that maps to one of existingFiles.
 * `readdirSync` returns a virtual directory listing derived from existingFiles.
 * `readFileSync` returns content from fileContents (keyed by POSIX-relative path).
 */
function makeFs(
  existingFiles: string[],
  // Keys are POSIX-relative to repo root, e.g. 'tests/foo.test.ts'
  fileContents: Record<string, string> = {},
): FsAdapter {
  // Canonical absolute paths that "exist" — keyed by norm(absPath).
  const existing = new Set(existingFiles.map((f) => norm(repoPath(f))));

  // Build a directory tree: Map<norm(absDir), Entry[]>
  const dirTree = new Map<string, Array<{ name: string; isDir: boolean }>>();

  function ensureDir(normDir: string): void {
    if (!dirTree.has(normDir)) dirTree.set(normDir, []);
  }

  for (const rel of existingFiles) {
    const parts = rel.split('/');
    let current = norm(REPO);
    ensureDir(current);

    for (let i = 0; i < parts.length - 1; i++) {
      const segment = parts[i]!;
      const childNorm = `${current}/${segment}`;
      const parentEntries = dirTree.get(current)!;
      if (!parentEntries.some((e) => e.name === segment)) {
        parentEntries.push({ name: segment, isDir: true });
      }
      ensureDir(childNorm);
      current = childNorm;
    }

    const fileName = parts[parts.length - 1]!;
    dirTree.get(current)!.push({ name: fileName, isDir: false });
  }

  // Build a content map keyed by norm(absPath) for readFileSync.
  const contentMap: Record<string, string> = {};
  for (const [rel, content] of Object.entries(fileContents)) {
    contentMap[norm(repoPath(rel))] = content;
  }

  return {
    existsSync(p: string): boolean {
      return existing.has(norm(p));
    },

    readdirSync(dir: string) {
      const key = norm(dir);
      return (dirTree.get(key) ?? []).map(({ name, isDir }) => ({
        name,
        isDirectory: () => isDir,
        isFile: () => !isDir,
      }));
    },

    readFileSync(p: string, _enc: 'utf8'): string {
      const key = norm(p);
      if (key in contentMap) return contentMap[key]!;
      throw Object.assign(new Error(`ENOENT: ${key}`), { code: 'ENOENT' });
    },
  };
}

